"""Render an 8D/CAPA report dict to a print-ready PDF."""
from __future__ import annotations

from io import BytesIO

from reportlab.graphics.charts.barcharts import VerticalBarChart
from reportlab.graphics.charts.linecharts import HorizontalLineChart
from reportlab.graphics.shapes import Drawing, String
from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

INK = colors.HexColor("#14161a")
MUTED = colors.HexColor("#5b616e")
ACCENT = colors.HexColor("#e8a317")
LINE = colors.HexColor("#d9dce1")
SOFT = colors.HexColor("#f4f5f7")


def _styles():
    ss = getSampleStyleSheet()
    return {
        "title": ParagraphStyle("t", parent=ss["Title"], fontName="Helvetica-Bold", fontSize=18, leading=22, textColor=INK, alignment=TA_LEFT, spaceAfter=2),
        "sub": ParagraphStyle("s", parent=ss["Normal"], fontSize=9, textColor=MUTED, leading=12),
        "h": ParagraphStyle("h", parent=ss["Heading2"], fontName="Helvetica-Bold", fontSize=11.5, textColor=INK, spaceBefore=10, spaceAfter=4),
        "body": ParagraphStyle("b", parent=ss["Normal"], fontSize=9.5, leading=13.5, textColor=INK),
        "bullet": ParagraphStyle("bl", parent=ss["Normal"], fontSize=9.5, leading=13.5, textColor=INK, leftIndent=10, bulletIndent=0),
        "small": ParagraphStyle("sm", parent=ss["Normal"], fontSize=8, leading=10, textColor=MUTED),
    }


def _bullets(items, st):
    return [Paragraph(str(i), st["bullet"], bulletText="•") for i in items]


def _bar_chart(by: dict | None, title: str) -> Drawing | None:
    if not by or not by.get("rows"):
        return None
    rows = by["rows"][:6]
    d = Drawing(80 * mm, 52 * mm)
    c = VerticalBarChart()
    c.x, c.y, c.width, c.height = 10 * mm, 10 * mm, 66 * mm, 34 * mm
    c.data = [[r["rate"] * 100 for r in rows]]
    c.categoryAxis.categoryNames = [str(r["key"]).replace("Supplier ", "Sup. ").replace("Furnace ", "F") for r in rows]
    c.categoryAxis.labels.fontSize = 7
    c.valueAxis.labels.fontSize = 7
    c.valueAxis.valueMin = 0
    c.bars[0].fillColor = ACCENT
    c.bars[0].strokeColor = None
    c.valueAxis.strokeColor = LINE
    c.categoryAxis.strokeColor = LINE
    d.add(c)
    d.add(String(10 * mm, 48 * mm, title, fontSize=8, fillColor=MUTED, fontName="Helvetica-Bold"))
    return d


def _trend_chart(series: list[dict]) -> Drawing | None:
    if not series:
        return None
    d = Drawing(80 * mm, 52 * mm)
    c = HorizontalLineChart()
    c.x, c.y, c.width, c.height = 10 * mm, 10 * mm, 66 * mm, 34 * mm
    c.data = [[s["rate"] * 100 for s in series]]
    c.categoryAxis.categoryNames = [s["period_start"] for s in series]
    c.categoryAxis.labels.fontSize = 7
    c.valueAxis.labels.fontSize = 7
    c.valueAxis.valueMin = 0
    c.lines[0].strokeColor = colors.HexColor("#d4483b")
    c.lines[0].strokeWidth = 2
    c.valueAxis.strokeColor = LINE
    c.categoryAxis.strokeColor = LINE
    d.add(c)
    d.add(String(10 * mm, 48 * mm, "Weekly defect rate (%)", fontSize=8, fillColor=MUTED, fontName="Helvetica-Bold"))
    return d


def render_pdf(r: dict) -> bytes:
    st = _styles()
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=14 * mm, bottomMargin=14 * mm,
                            title=r.get("title", "8D report"), author="InspectAgent")
    part = r.get("part", {})
    story = [
        Table([[""]], colWidths=[doc.width], rowHeights=[3], style=[("BACKGROUND", (0, 0), (-1, -1), ACCENT)]),
        Spacer(1, 6),
        Paragraph(r.get("title", "8D Report"), st["title"]),
        Paragraph(f"{part.get('name', '')} &middot; {part.get('id', '')} &middot; {part.get('material', '')} &middot; "
                  f"Generated by InspectAgent on {r.get('date', '')}", st["sub"]),
        Spacer(1, 8),
    ]
    charts = r.get("charts") or {}
    by = charts.get("by") or {}
    cells = [x for x in (_trend_chart(charts.get("trend") or []), _bar_chart(next(iter(by.values()), None), f"Rate by {next(iter(by), '')} (%)")) if x]
    if cells:
        story.append(Table([cells], colWidths=[doc.width / 2] * len(cells),
                           style=[("BOX", (0, 0), (-1, -1), 0.5, LINE), ("BACKGROUND", (0, 0), (-1, -1), SOFT)]))

    def section(code, title, flow):
        story.append(KeepTogether([Paragraph(f"<font color='#e8a317'>{code}</font>&nbsp;&nbsp;{title}", st["h"]), *flow]))

    section("D1", "Team", _bullets(r.get("d1_team", []), st))
    section("D2", "Problem description", [Paragraph(r.get("d2_problem", ""), st["body"])])
    section("D3", "Containment actions", _bullets(r.get("d3_containment", []), st))
    rc = r.get("d4_root_cause", {})
    flow = [Paragraph(f"<b>{rc.get('statement', '')}</b>", st["body"]), Spacer(1, 4), Paragraph("Evidence", st["small"])]
    flow += _bullets(rc.get("evidence", []), st)
    if rc.get("five_whys"):
        flow += [Spacer(1, 4), Paragraph("5 Whys", st["small"])]
        flow += [Paragraph(f"{i + 1}. {w}", st["bullet"]) for i, w in enumerate(rc["five_whys"])]
    section("D4", "Root cause analysis", flow)
    rows = [["Action", "Owner", "Due"]] + [[Paragraph(a["action"], st["body"]), a["owner"], a["due"]] for a in r.get("d5_corrective_actions", [])]
    t = Table(rows, colWidths=[doc.width * 0.62, doc.width * 0.24, doc.width * 0.14], repeatRows=1)
    t.setStyle(TableStyle([
        ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 8.5), ("TEXTCOLOR", (0, 0), (-1, 0), MUTED),
        ("FONT", (1, 1), (-1, -1), "Helvetica", 9), ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LINEBELOW", (0, 0), (-1, -1), 0.4, LINE), ("BACKGROUND", (0, 0), (-1, 0), SOFT),
        ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    section("D5", "Permanent corrective actions", [t])
    section("D6", "Implementation & verification", [Paragraph(r.get("d6_verification", ""), st["body"])])
    section("D7", "Prevent recurrence", _bullets(r.get("d7_prevention", []), st))
    section("D8", "Closure", [Paragraph(r.get("d8_closure", ""), st["body"])])
    story += [Spacer(1, 14), Paragraph("Draft generated by InspectAgent (SAM 3.1 + Muse Spark). Review and approve before release.", st["small"])]
    doc.build(story)
    return buf.getvalue()
